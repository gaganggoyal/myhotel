export type Locale = "en" | "hi";
const DICTS: Record<Locale, Dict> = { en, hi };

export function t(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  let s = DICTS[locale][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function translator(locale: Locale) {
  return (key: DictKey, vars?: Record<string, string | number>) => t(locale, key, vars);
}
